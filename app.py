"""Sri Lankan dengue one-month-ahead demonstration dashboard.
Uses the exact features and saved estimator from the course notebook.
"""
from pathlib import Path
import io
import joblib
import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt

st.set_page_config(page_title='Sri Lanka Dengue Forecast', page_icon='🦟', layout='wide')
ROOT = Path(__file__).resolve().parent
st.title('🦟 Sri Lanka Dengue Forecast Dashboard')
st.caption('Historical case-count model • One-month-ahead forecasts • Educational demonstration')

@st.cache_resource
def load_model(path: str):
    artifact = joblib.load(path)  # Only load locally created/trusted pickle files.
    if not isinstance(artifact, dict) or not {'model', 'features'}.issubset(artifact):
        raise ValueError('Invalid model artifact: expected model and features.')
    return artifact

@st.cache_data
def load_excel(path: str):
    return pd.read_excel(path, sheet_name='All Data', usecols='A:C')

def prepare_data(raw):
    columns = {c.strip().lower(): c for c in raw.columns}
    required = ['date','city','value']
    if not all(k in columns for k in required):
        raise ValueError('Data must contain Date, City, Value columns.')
    df = raw.rename(columns={columns['date']:'date', columns['city']:'city', columns['value']:'cases'})[['date','city','cases']].copy()
    df['date'] = pd.to_datetime(df['date'], errors='coerce')
    df['city'] = df['city'].astype('string').str.strip()
    df['cases'] = pd.to_numeric(df['cases'], errors='coerce')
    if df[['date','city','cases']].isna().any().any():
        raise ValueError('Date, City or Value has missing/invalid entries.')
    if not df['date'].dt.is_month_start.all():
        raise ValueError('Dates must be the first day of each month.')
    if (df['cases'] < 0).any():
        raise ValueError('Case counts cannot be negative.')
    if df.duplicated(['city','date']).any():
        raise ValueError('Duplicate city/month records found.')
    return df.sort_values(['city','date']).reset_index(drop=True)

def make_features(history, city, features):
    series = history[history['city'].eq(city)].set_index('date')['cases'].sort_index()
    if len(series) < 12:
        raise ValueError('At least 12 monthly observations are required.')
    expected = pd.date_range(series.index.min(), series.index.max(), freq='MS')
    if len(expected) != len(series) or not expected.equals(pd.DatetimeIndex(series.index)):
        raise ValueError('Missing month(s) in the selected location. Upload a complete monthly series.')
    next_month = series.index.max() + pd.DateOffset(months=1)
    recent = series.to_numpy(dtype=float)
    row = {name: 0.0 for name in features}
    row.update({'lag_1':recent[-1], 'lag_2':recent[-2], 'lag_3':recent[-3],
                'lag_12':recent[-12], 'roll_mean_3':recent[-3:].mean(),
                'roll_mean_6':recent[-6:].mean(), 'year':next_month.year,
                'month_sin':np.sin(2*np.pi*next_month.month/12),
                'month_cos':np.cos(2*np.pi*next_month.month/12)})
    key = f'city_{city}'
    city_columns = [f for f in features if f.startswith('city_')]
    if key not in city_columns:
        raise ValueError(f'Location {city!r} is not present in the trained model.')
    row[key] = 1.0
    unknown = [f for f in features if f not in row]
    if unknown:
        raise ValueError(f'Unsupported model feature(s): {unknown}')
    return pd.DataFrame([row], columns=features), next_month, series

model_path = ROOT / 'dengue_model_tuned.pkl'
if not model_path.exists():
    st.error('Missing dengue_model_tuned.pkl. Copy it from the VS Code notebook output folder into this app folder.')
    st.stop()
try:
    artifact = load_model(str(model_path))
except Exception as exc:
    st.error(f'Could not load the model: {exc}')
    st.stop()

with st.sidebar:
    st.header('Data source')
    st.info('Use only a trusted .pkl file generated by your own notebook.')
    uploaded = st.file_uploader('Optional updated monthly dataset (CSV or XLSX)', type=['csv','xlsx'])
    st.caption('Required columns: Date, City, Value. One record per location per month.')

try:
    if uploaded is not None:
        raw = pd.read_csv(uploaded) if uploaded.name.lower().endswith('.csv') else pd.read_excel(uploaded)
        data_source = f'Uploaded: {uploaded.name}'
    else:
        excel = ROOT / 'Dengue_Data (2010-2020).xlsx'
        if not excel.exists():
            st.error('Missing Dengue_Data (2010-2020).xlsx. Copy the original Excel dataset into the app folder or upload a CSV/XLSX from the sidebar.')
            st.stop()
        raw = load_excel(str(excel))
        data_source = 'Original historical Excel dataset'
    df = prepare_data(raw)
except Exception as exc:
    st.error(f'Data validation failed: {exc}')
    st.stop()

model = artifact['model']
features = list(artifact['features'])
known_cities = {f.removeprefix('city_') for f in features if f.startswith('city_')}
locations = sorted(set(df['city'].dropna()) & known_cities)
if not locations:
    st.error('No uploaded locations match the trained model city categories.')
    st.stop()
with st.sidebar:
    city = st.selectbox('Select reporting location', locations, index=locations.index('Colombo') if 'Colombo' in locations else 0)
    st.caption(f'Model: {artifact.get("model_name", "Saved estimator")}')
    st.caption(f'Dataset: {data_source}')

try:
    X, next_month, series = make_features(df, city, features)
    prediction = max(0.0, float(model.predict(X)[0]))
except Exception as exc:
    st.error(f'Cannot predict for this location: {exc}')
    st.stop()

st.warning('This model was trained on 2010–2018 observations and evaluated on 2019–2020 data. Predictions using later dates are out-of-period and have not been validated. The forecast is not a clinical or public-health alert.')
col1,col2,col3 = st.columns(3)
col1.metric('Forecast month', next_month.strftime('%B %Y'))
col2.metric('Predicted cases', f'{prediction:,.0f}')
col3.metric('Most recent observed month', series.index.max().strftime('%b %Y'))
st.caption(f'Previous observed count: {series.iloc[-1]:,.0f} • Same month last year: {series.iloc[-12]:,.0f}')

st.subheader(f'Historical dengue counts — {city}')
fig, ax = plt.subplots(figsize=(10,3.5))
ax.plot(series.index, series.values, label='Reported cases')
ax.scatter([next_month],[prediction], marker='D', s=75, label='Next-month model forecast')
ax.plot([series.index[-1],next_month],[series.iloc[-1],prediction],linestyle='--',alpha=0.6)
ax.set_ylabel('Cases'); ax.set_xlabel('Month'); ax.legend(); fig.tight_layout()
st.pyplot(fig); plt.close(fig)

with st.expander('See model input features'):
    st.dataframe(X.T.rename(columns={0:'Value'}), use_container_width=True)

st.subheader('Model performance on the historical test period')
comparison_path = ROOT / 'dengue_full_model_comparison.csv'
if comparison_path.exists():
    comparison = pd.read_csv(comparison_path, index_col=0)
    st.dataframe(comparison.round(3), use_container_width=True)
else:
    st.caption('Copy dengue_full_model_comparison.csv into this folder to show your actual evaluated metrics.')

with st.expander('Explain this prediction with SHAP (optional)'):
    if st.button('Calculate SHAP explanation'):
        try:
            import shap
            with st.spinner('Calculating SHAP contributions…'):
                explainer = shap.TreeExplainer(model)
                values = explainer(X)
                contributions = pd.Series(values.values[0], index=features)
                top = contributions.reindex(contributions.abs().sort_values(ascending=False).head(12).index).sort_values()
                fig2, ax2 = plt.subplots(figsize=(9,4))
                ax2.barh(top.index, top.values)
                ax2.set_xlabel('SHAP contribution to predicted case count')
                fig2.tight_layout()
                st.pyplot(fig2); plt.close(fig2)
            st.caption('SHAP describes model contributions, not causal risk factors. Negative forecasts are clipped to zero in the dashboard.')
        except Exception as exc:
            st.warning(f'SHAP explanation unavailable: {exc}')

